#!/usr/bin/env node
// Слід · тести перевірки милозвучності (tools/euphony.mjs; УП 2019 § 23–25). Приклади правил — із самого правопису.
// Кожне правило: випадок, що має спрацювати, і випадок, що не має (зокрема хибні правки, які відкотив verifier-euphony 02.11).
// Запуск: node tools/test-euphony.mjs
import { euphony } from "./euphony.mjs";

let fail = 0, n = 0;
const hits = t => euphony(t).map(x => `${x.found}→${x.want}`);
const has = (t, exp, msg) => { n++; const h = hits(t); if (!(h.length === 1 && h[0] === exp)) { fail++; console.log(`✗ ${msg}\n   «${t}»: ${JSON.stringify(h)}, очікувано ${exp}`); } };
const none = (t, msg) => { n++; const h = hits(t); if (h.length) { fail++; console.log(`✗ ${msg}\n   «${t}»: зайве ${JSON.stringify(h)}`); } };

/* § 23 у/в */
has("Брат в школі.", "Брат в школі→у", "в між приголосними");
none("Брат у школі.", "у між приголосними — чисто");
has("Сидимо в вагоні.", "Сидимо в вагоні→у", "в перед в");
has("Діти побували в Львові.", "побували в Львові→у", "в перед льв (після голосного теж)");
has("Він прийшов, в руках квіти.", "в руках→у", "в після паузи перед приголосним");
none("В лісі пахло квітами.", "В на початку речення перед приголосним — допустимо (примітка 1)");
has("Вона побувала у Одесі.", "побувала у Одесі→в", "у між голосними");
has("У Антарктиді працюють.", "У Антарктиді→В", "У на початку речення перед голосним");
has("Вартовий поглянув у отвір.", "поглянув у отвір→в", "у після приголосного перед голосним");
has("Пішла у садок.", "Пішла у садок→в", "у після голосного перед приголосним");
none("Пішла у вишневий садок.", "у перед в — чисто");
none("Вона прожила в Японії.", "в після голосного — чисто");
none("Подія сталася 1990 р. в місті.", "після скорочення «р.» — не перевіряється");
none("Банк в НБУ і в 1991 році.", "абревіатура й цифра — не перевіряються");
/* § 24 і/й */
has("Й ось настала весна.", "Й ось→І", "Й на початку речення");
has("Брат й сестра.", "Брат й сестра→і", "й між приголосними");
has("Ольга й Юрій.", "Ольга й Юрій→і", "й перед ю");
has("Мрія й надія.", "Мрія й надія→і", "й після я (§ 24 п. 4)");
has("Пісня, й танець.", "й танець→і", "й після паузи перед приголосним");
none("Ольга й Андрій.", "й між голосними — чисто");
has("Ольга і Андрій.", "Ольга і Андрій→й", "і між голосними");
none("Мрії і обіцянки.", "і після ї — лише «і» (§ 24 п. 4; правку відкочено 02.11)");
none("Небо синіє і журавлі курличуть.", "і після є — чисто (відкочено 02.11)");
none("Дні і ночі, мама і тато.", "і між голосним і приголосним — не перевіряється (зіставлення понять)");
none("«Хто це?» і він пішов.", "після питання в лапках — не перевіряється (відкочено 02.11)");
none("Князь Данило І Романович.", "велика І всередині речення — не сполучник");
/* § 25 з/із/зі */
has("Він прийшов з сестрою.", "прийшов з сестрою→із", "з між приголосними перед с");
has("З села приїхали діти.", "З села→Із", "З на початку речення перед одиничним с");
has("З школи вийшли діти.", "З школи→Зі", "З перед збігом шк — «Зі школи» (приклад § 25)");
has("Гра — з шахами.", "з шахами→із", "з після тире перед ш");
none("Вона прийшла з сестрою.", "з після голосного перед с — не перевіряється (питання людині)");
has("Бере книжку з стола.", "книжку з стола→зі", "з перед збігом ст");
has("Він був з мною.", "був з мною→зі", "з мною");
has("Робота із української мови.", "Робота із української→з", "із перед голосним");
none("Лист із Бразилії.", "із між приголосними перед б — чисто");
none("Зі школи на майдан.", "зі перед шк — чисто");
none("З одним рибалкою подружив.", "З перед голосним — чисто");
/* що не перевіряється */
none("Обери у чи в. Після й і пишемо інакше. Вибери з, із чи зі.", "назви літер і прийменників — не вжиток");
none("Перед в пишемо у. Прийменник з часто стоїть перед словом.", "назва літери після «перед», «прийменник»");
none("Наприклад: <i>брат в школі</i>, «Брат в школі».", "приклади й цитати");
none("Не <s>в вагоні</s>, а у вагоні.", "закреслене");
none("Звук [в] у слові.", "транскрипція");
has("<p>Тема</p><p>У Африці жарко.</p>", "У Африці→В", "межа блоку — початок речення");
none("<b>у</b> школі", "мала літера на початку поля — невідомий контекст");

console.log(fail ? `test-euphony: ${fail} з ${n} не пройшли` : `test-euphony: ${n} перевірок — усі пройшли`);
process.exit(fail ? 1 : 0);
